#!/usr/bin/env node
// Packages web/ for the ESP32: gzips every asset and emits a C header of PROGMEM byte arrays.
// Usage: node tools/build-web.mjs [--out build/web] [--header path/to/web_assets.h]
// See docs/web-ui.md ("Porting to firmware").

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { gzipSync, constants } from 'node:zlib';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'web');

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, arr) => (a.startsWith('--') ? [...acc, [a.slice(2), arr[i + 1]]] : acc), []),
);
const OUT = path.resolve(ROOT, args.out || 'build/web');
const HEADER = path.resolve(ROOT, args.header || path.join(OUT, 'web_assets.h'));

// Flash budget warning threshold for the gzipped UI (ESP32-S3 N16: 16 MB flash, two OTA slots).
const BUDGET_BYTES = 150 * 1024;

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
};

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out.sort();
}

function cIdent(urlPath) {
  return 'ASSET_' + urlPath.replace(/^\//, '').replace(/[^A-Za-z0-9]/g, '_').toUpperCase();
}

function cBytes(buf) {
  const lines = [];
  for (let i = 0; i < buf.length; i += 20) {
    lines.push('  ' + [...buf.subarray(i, i + 20)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(','));
  }
  return lines.join(',\n');
}

const files = await walk(SRC);
const assets = [];
for (const file of files) {
  const rel = path.relative(SRC, file).split(path.sep).join('/');
  const ext = path.extname(file);
  const mime = MIME[ext];
  if (!mime) { console.warn(`  skip (unknown type): ${rel}`); continue; }
  const raw = await readFile(file);
  const gz = gzipSync(raw, { level: constants.Z_BEST_COMPRESSION });
  const etag = '"' + createHash('sha1').update(raw).digest('hex').slice(0, 12) + '"';
  const urlPath = '/' + rel;
  assets.push({ urlPath, mime, raw, gz, etag });
  await mkdir(path.dirname(path.join(OUT, rel)), { recursive: true });
  await writeFile(path.join(OUT, rel + '.gz'), gz);
}

const header = `// GENERATED by tools/build-web.mjs from web/ — do not edit by hand.
// ${assets.length} assets, ${assets.reduce((n, a) => n + a.gz.length, 0)} bytes gzipped.
#pragma once
#include <Arduino.h>

struct WebAsset {
  const char *path;       // URL path, e.g. "/js/app.js"
  const char *mime;       // Content-Type
  const char *etag;       // strong ETag of the uncompressed file
  const uint8_t *data;    // gzip body (serve with Content-Encoding: gzip)
  size_t length;
};

${assets.map((a) => `static const uint8_t ${cIdent(a.urlPath)}[] PROGMEM = {\n${cBytes(a.gz)}\n};`).join('\n\n')}

static const WebAsset WEB_ASSETS[] = {
${assets.map((a) => `  { "${a.urlPath}", "${a.mime}", ${JSON.stringify(a.etag)}, ${cIdent(a.urlPath)}, sizeof(${cIdent(a.urlPath)}) },`).join('\n')}
};

static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);
`;
await mkdir(path.dirname(HEADER), { recursive: true });
await writeFile(HEADER, header);

const total = assets.reduce((n, a) => n + a.gz.length, 0);
const rawTotal = assets.reduce((n, a) => n + a.raw.length, 0);
const pad = (s, n) => String(s).padEnd(n);
console.log('\n  ACORN web assets\n');
console.log(`  ${pad('path', 28)}${pad('raw', 10)}gzip`);
for (const a of assets) console.log(`  ${pad(a.urlPath, 28)}${pad((a.raw.length / 1024).toFixed(1) + ' KB', 10)}${(a.gz.length / 1024).toFixed(1)} KB`);
console.log(`  ${pad('total', 28)}${pad((rawTotal / 1024).toFixed(1) + ' KB', 10)}${(total / 1024).toFixed(1)} KB`);
console.log(`\n  gz files -> ${path.relative(ROOT, OUT)}/`);
console.log(`  header   -> ${path.relative(ROOT, HEADER)}\n`);
if (total > BUDGET_BYTES) {
  console.warn(`  WARNING: gzipped UI exceeds ${BUDGET_BYTES / 1024} KB budget.\n`);
  process.exitCode = 1;
}
